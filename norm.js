// Нормалізація коду моделі: великі літери, лише A-Z0-9.
// ВАЖЛИВО: точно така сама нормалізація має бути у фронтенді,
// щоб пошук "SMV68" знаходив "SMV68IX00D/01".
//
// Живе окремим файлом (а не в db.js), щоб її могли використовувати модулі
// без підключення до бази — напр. пошук товару на донорі.
function norm(s) {
  return String(s || '').toUpperCase().replace(/[^A-Z0-9]/g, '');
}

module.exports = { norm };
